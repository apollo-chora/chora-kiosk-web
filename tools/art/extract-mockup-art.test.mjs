import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync, readdirSync } from 'node:fs';

import { CARD_NAMES, CROP_DIR, CROP_NAMES, OUT, crops, render } from './extract-mockup-art.mjs';

const svg = (n) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 190"><rect id="${n}"/></svg>`;
const ART = Object.fromEntries(CARD_NAMES.map((n) => [n, svg(n)]));

test('names the hall’s four cards, then the Engine Room’s four tiles, in the mockup’s order', () => {
  assert.deepEqual(CARD_NAMES, ['card_maps', 'card_dash', 'card_grade', 'card_engine', 'tile_crews', 'tile_safety', 'tile_gov', 'tile_local']);
});

test('writes each card’s markup verbatim, in order, as a typed table', () => {
  const text = render(ART);
  assert.match(text, /^\/\/ Generated by tools\/art\/extract-mockup-art\.mjs/);
  assert.match(text, /export const CARD_ART = \{\n/);
  assert.match(text, /export type CardArtName = keyof typeof CARD_ART;\n$/);
  const at = CARD_NAMES.map((n) => text.indexOf(`  ${n}: ${JSON.stringify(svg(n))},`));
  assert.ok(at.every((i) => i > 0), `every card is in the table: ${at}`);
  assert.deepEqual([...at].sort((a, b) => a - b), at);
});

test('leaves out the mockup’s other drawings', () => {
  const text = render({ ...ART, illus: svg('illus'), tile_other: svg('tile_other') });
  assert.equal(text.includes('illus'), false);
  assert.equal(text.includes('tile_other'), false);
});

test('refuses a card the mockup does not draw', () => {
  const { card_grade: _gone, ...rest } = ART;
  assert.throws(() => render(rest), /card_grade/);
});

test('refuses a card that is not one svg element', () => {
  assert.throws(() => render({ ...ART, card_dash: '<img src="x.png">' }), /card_dash is not an svg/);
  assert.throws(() => render({ ...ART, card_dash: `${svg('a')}<script></script>` }), /card_dash is not an svg/);
});

test('refuses a card that loads anything (the kiosk runs offline)', () => {
  assert.throws(
    () => render({ ...ART, card_maps: '<svg xmlns="http://www.w3.org/2000/svg"><image href="https://x.test/a.png"/></svg>' }),
    /card_maps loads/,
  );
});

test('the committed table holds exactly the cards and tiles (its contents are checked by mockup:check)', () => {
  const committed = readFileSync(OUT, 'utf8');
  const names = [...committed.matchAll(/^ {2}([a-z_]+): "<svg /gm)].map((m) => m[1]);
  assert.deepEqual(names, CARD_NAMES);
});

// The AI-safety page's evidence crops (K74): the mockup's SAFETY_IMG data URIs, as PNG files.
const PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 1, 2, 3]);
const IMG = Object.fromEntries(CROP_NAMES.map((n) => [n, `data:image/png;base64,${PNG.toString('base64')}`]));

test('names the eight evidence crops the safety page shows', () => {
  assert.deepEqual(CROP_NAMES, ['judge-floors', 'judge-oplus', 'redteam-six-blocked', 'gate-blocked-leak', 'gate-crew-nothing', 'runtime-armor', 'drift-gate-planted', 'drift-record']);
});

test('decodes each crop to its PNG bytes', () => {
  const out = crops(IMG);
  assert.deepEqual([...out.keys()], CROP_NAMES);
  assert.ok(out.get('judge-floors').equals(PNG));
});

test('refuses a crop the mockup does not hold, one that is not a PNG data URI, and bytes that are not a PNG', () => {
  const { 'drift-record': _gone, ...rest } = IMG;
  assert.throws(() => crops(rest), /drift-record/);
  assert.throws(() => crops({ ...IMG, 'judge-oplus': 'https://x.test/a.png' }), /judge-oplus is not a PNG data URI/);
  assert.throws(() => crops({ ...IMG, 'judge-oplus': `data:image/png;base64,${Buffer.from('GIF89a').toString('base64')}` }), /judge-oplus is not a PNG/);
});

test('the committed crops are exactly the eight PNGs (their bytes are checked by mockup:check)', () => {
  const names = readdirSync(CROP_DIR).sort();
  assert.deepEqual(names, CROP_NAMES.map((n) => `${n}.png`).sort());
});
