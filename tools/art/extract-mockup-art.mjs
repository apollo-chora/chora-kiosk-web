#!/usr/bin/env node
// The Explore hall's card drawings and the Engine Room's tiles, read from the approved mockup as
// its script leaves them (ART.card_maps, card_grade and card_engine, ART.card_dash, which a later
// script block adds, and ART.tile_crews, tile_safety, tile_gov and tile_local). Verbatim, because
// the mockup's stylesheet sizes them as inline svg. The mockup's ART.illus is drawn nowhere. Also
// the AI-safety page's evidence crops (K74, the mockup's SAFETY_IMG data URIs) as PNG files.
// Writes src/app/shared/art/card-art.ts and public/assets/safety/*.png; --check exits 1 when the
// committed table or any crop differs, or a crop file is missing or extra.
//
// Usage: node tools/art/extract-mockup-art.mjs [--check]
import { chromium } from '@playwright/test';
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const MOCKUP = join(ROOT, '..', 'docs', 'design', 'kiosk', 'apollo-kiosk-mockup.html');
export const OUT = join(ROOT, 'src', 'app', 'shared', 'art', 'card-art.ts');
export const CROP_DIR = join(ROOT, 'public', 'assets', 'safety');

/**
 * The hall's cards in the mockup's order (SCENES.hall; the Companions card draws its Companions
 * instead), then the Engine Room's tiles in its order (SCENES.engine).
 */
export const CARD_NAMES = ['card_maps', 'card_dash', 'card_grade', 'card_engine', 'tile_crews', 'tile_safety', 'tile_gov', 'tile_local'];

/** The safety page's evidence crops (SAFETY_IMG), in the order its five stages show them. */
export const CROP_NAMES = ['judge-floors', 'judge-oplus', 'redteam-six-blocked', 'gate-blocked-leak', 'gate-crew-nothing', 'runtime-armor', 'drift-gate-planted', 'drift-record'];
const PNG_SIGNATURE = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const PNG_URI = 'data:image/png;base64,';

const ONE_SVG = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg"[^>]*>[\s\S]*<\/svg>$/;

async function read() {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    await page.goto('file://' + MOCKUP);
    return await page.evaluate(() => ({ art: { ...ART }, imgs: { ...SAFETY_IMG } }));
  } finally {
    await browser.close();
  }
}

/** Each evidence crop's PNG bytes, by name; refuses a missing crop or one that is not a PNG. */
export function crops(imgs) {
  const out = new Map();
  for (const name of CROP_NAMES) {
    const uri = imgs[name];
    if (typeof uri !== 'string') throw new Error(`the mockup holds no SAFETY_IMG['${name}']`);
    if (!uri.startsWith(PNG_URI)) throw new Error(`${name} is not a PNG data URI`);
    const bytes = Buffer.from(uri.slice(PNG_URI.length), 'base64');
    if (!bytes.subarray(0, 8).equals(PNG_SIGNATURE)) throw new Error(`${name} is not a PNG`);
    out.set(name, bytes);
  }
  return out;
}

export function render(art) {
  const lines = CARD_NAMES.map((name) => {
    const markup = art[name];
    if (typeof markup !== 'string') throw new Error(`the mockup draws no ART.${name}`);
    if (!ONE_SVG.test(markup) || markup.indexOf('</svg>') !== markup.length - 6) throw new Error(`${name} is not an svg element`);
    // The namespace is the only URL a card may name: nothing is fetched, the kiosk runs offline.
    if (/href=|url\(|https?:\/\/(?!www\.w3\.org\/2000\/svg")/.test(markup)) throw new Error(`${name} loads something from outside the drawing`);
    return `  ${name}: ${JSON.stringify(markup)},`;
  });
  return (
    '// Generated by tools/art/extract-mockup-art.mjs from the approved mockup (the hall cards and the\n' +
    '// Engine Room tiles of ART), verbatim. Do not edit by hand. Inline svg: the kiosk runs offline and the\n' +
    '// stylesheet sizes the svg.\n' +
    'export const CARD_ART = {\n' +
    lines.join('\n') +
    '\n} as const;\n\nexport type CardArtName = keyof typeof CARD_ART;\n'
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { art, imgs } = await read();
  const text = render(art);
  const pngs = crops(imgs);
  if (process.argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(OUT, 'utf8');
    } catch {
      committed = '';
    }
    const problems = [];
    if (committed !== text) problems.push('card-art.ts differs from the mockup');
    let files = [];
    try {
      files = readdirSync(CROP_DIR);
    } catch {
      files = [];
    }
    const wanted = new Set(CROP_NAMES.map((n) => `${n}.png`));
    for (const f of files) if (!wanted.has(f)) problems.push(`public/assets/safety holds ${f}, which the mockup does not`);
    for (const [name, bytes] of pngs) {
      let held = null;
      try {
        held = readFileSync(join(CROP_DIR, `${name}.png`));
      } catch {
        held = null;
      }
      if (!held || !held.equals(bytes)) problems.push(`${name}.png differs from the mockup's crop`);
    }
    process.stdout.write(problems.length ? `art: CHECK FAIL, ${problems.join('; ')}\n` : 'art: CHECK PASS\n');
    process.exit(problems.length ? 1 : 0);
  }
  writeFileSync(OUT, text);
  mkdirSync(CROP_DIR, { recursive: true });
  for (const [name, bytes] of pngs) writeFileSync(join(CROP_DIR, `${name}.png`), bytes);
  process.stdout.write(`art: wrote ${OUT} and ${pngs.size} crops in ${CROP_DIR}\n`);
}
