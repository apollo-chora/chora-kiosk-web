#!/usr/bin/env node
// T3.5: the kiosk's look, ported from the approved mockup's stylesheet.
//
// The mockup's CSS is one cascade layered version by version (a later rule overrides an
// earlier one), so kiosk-web keeps it whole, in order, as src/styles/mockup.css, and its
// components use the same class names and structure. Two things are left out:
//   - the :root tokens block: src/styles/_kiosk-tokens.scss holds those values with the
//     bundled Inter first in the font stack;
//   - the Review drawer (#review, #review-btn): a mockup tool, never kiosk UI.
// Kiosk-only additions live in their own file, never here, so this one stays checkable.
//
// Usage: node tools/styles/extract-mockup-css.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const MOCKUP = join(ROOT, '..', 'docs', 'design', 'kiosk', 'apollo-kiosk-mockup.html');
const OUT = join(ROOT, 'src', 'styles', 'mockup.css');

const HEADER =
  '/* Generated by tools/styles/extract-mockup-css.mjs from docs/design/kiosk/apollo-kiosk-mockup.html\n' +
  '   (Version 6, approved, K86). Do not edit: kiosk additions go in _kiosk-additions.scss.\n' +
  '   Left out: the :root tokens (_kiosk-tokens.scss) and the mockup-only Review drawer. */\n';

export function extractCss(html) {
  const m = /<style>\n?([\s\S]*?)<\/style>/.exec(html);
  if (!m) throw new Error('no <style> block in the mockup');
  const lines = m[1].split('\n');
  const out = [];
  let inRoot = false;
  for (const line of lines) {
    if (inRoot) {
      if (/^\}/.test(line)) inRoot = false;
      continue;
    }
    if (/^:root\s*\{/.test(line)) {
      inRoot = !/\}\s*$/.test(line);
      continue;
    }
    if (/^\/\* ===== Tokens:/.test(line) || /^\/\* ===== Review drawer/.test(line)) continue;
    if (/^#review/.test(line)) {
      if (!/\}\s*$/.test(line)) throw new Error(`a #review rule spans lines: ${line}`);
      continue;
    }
    out.push(line);
  }
  return out.join('\n').replace(/^\n+/, '').replace(/\n*$/, '\n');
}

function main() {
  const css = HEADER + extractCss(readFileSync(MOCKUP, 'utf8'));
  if (process.argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(OUT, 'utf8');
    } catch {
      committed = '';
    }
    const same = committed === css;
    process.stdout.write(same ? 'mockup css: CHECK PASS\n' : `mockup css: CHECK FAIL, ${OUT} differs from the mockup\n`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, css);
  process.stdout.write(`mockup css: wrote ${css.length} bytes\n`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
