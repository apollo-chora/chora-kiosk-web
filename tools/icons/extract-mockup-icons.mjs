#!/usr/bin/env node
// The kiosk's inline SVG icons, read from the approved mockup as its script leaves them:
// ICON (with later additions such as ICON.ai), DB_ICON, and the header's Credits mark.
// Verbatim, because the mockup's stylesheet sizes some icons by their own class or
// width and height attributes (".stamp .clock"). Writes src/app/shared/icon/icons.ts;
// --check exits 1 when the committed table differs.
//
// Usage: node tools/icons/extract-mockup-icons.mjs [--check]
import { chromium } from '@playwright/test';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const MOCKUP = join(ROOT, '..', 'docs', 'design', 'kiosk', 'apollo-kiosk-mockup.html');
const OUT = join(ROOT, 'src', 'app', 'shared', 'icon', 'icons.ts');

async function read() {
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    await page.goto('file://' + MOCKUP);
    return await page.evaluate(() => ({
      icon: ICON,
      db: DB_ICON,
      credits: document.querySelector('.chip-credits svg').outerHTML,
    }));
  } finally {
    await browser.close();
  }
}

export function render({ icon, db, credits }) {
  const all = { ...icon, ...db, credits };
  const clash = Object.keys(db).filter((k) => k in icon);
  if (clash.length) throw new Error(`icon names in both ICON and DB_ICON: ${clash.join(', ')}`);
  const lines = Object.entries(all).map(([k, v]) => `  ${/^[a-z_]+$/.test(k) ? k : JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return (
    '// Generated by tools/icons/extract-mockup-icons.mjs from the approved mockup (ICON, DB_ICON and\n' +
    "// the header's Credits mark), verbatim. Do not edit by hand.\n" +
    '// No icon font and no CDN: the kiosk runs offline. Each drawing uses currentColor.\n' +
    'export const ICONS = {\n' +
    lines.join('\n') +
    '\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n'
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render(await read());
  if (process.argv.includes('--check')) {
    let committed = '';
    try {
      committed = readFileSync(OUT, 'utf8');
    } catch {
      committed = '';
    }
    const same = committed === text;
    process.stdout.write(same ? 'icons: CHECK PASS\n' : 'icons: CHECK FAIL, icons.ts differs from the mockup\n');
    process.exit(same ? 0 : 1);
  }
  writeFileSync(OUT, text);
  process.stdout.write(`icons: wrote ${OUT}\n`);
}
